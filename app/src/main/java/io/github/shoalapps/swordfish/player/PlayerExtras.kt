package io.github.shoalapps.swordfish.player

import io.github.shoalapps.swordfish.AppGraph
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.Request
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo

/** One line of captions on screen between [startMs] and [endMs]. */
data class Cue(val startMs: Long, val endMs: Long, val text: String)

data class CaptionTrack(val label: String, val url: String, val auto: Boolean)

data class Chapter(val title: String, val startMs: Long, val thumbnail: String?)

object Captions {
    fun tracks(info: StreamInfo): List<CaptionTrack> =
        info.subtitles
            .filter { it.isUrl && it.format == MediaFormat.VTT }
            .map { CaptionTrack(it.displayLanguageName + if (it.isAutoGenerated) " (auto-generated)" else "", it.content, it.isAutoGenerated) }
            .distinctBy { it.label }
            .sortedBy { it.auto }

    suspend fun load(track: CaptionTrack): List<Cue> = withContext(Dispatchers.IO) {
        val req = Request.Builder().url(track.url).header("User-Agent", io.github.shoalapps.swordfish.data.NewPipeDownloader.USER_AGENT).build()
        val body = AppGraph.http.newCall(req).execute().use { it.body?.string().orEmpty() }
        parseVtt(body)
    }

    private val timeLine = Regex("""(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})\s+-->\s+(\d{1,2}:)?(\d{2}):(\d{2})[.,](\d{3})""")
    private val tags = Regex("""<[^>]+>""")

    private fun ms(h: String?, m: String, s: String, f: String) =
        ((h?.trimEnd(':')?.toLongOrNull() ?: 0) * 3600 + m.toLong() * 60 + s.toLong()) * 1000 + f.toLong()

    /**
     * Small WebVTT reader. YouTube's auto-captions repeat the previous line in each cue,
     * so only the newest line of each cue is kept for those.
     */
    fun parseVtt(text: String): List<Cue> {
        val cues = mutableListOf<Cue>()
        val lines = text.replace("\r", "").split("\n")
        var i = 0
        while (i < lines.size) {
            val m = timeLine.find(lines[i])
            if (m == null) { i++; continue }
            val g = m.groupValues
            val start = ms(g[1].ifEmpty { null }, g[2], g[3], g[4])
            val end = ms(g[5].ifEmpty { null }, g[6], g[7], g[8])
            i++
            val body = mutableListOf<String>()
            while (i < lines.size && lines[i].isNotBlank()) {
                body += lines[i].replace(tags, "").replace("&amp;", "&").replace("&gt;", ">").replace("&lt;", "<").replace("&#39;", "'").replace("&quot;", "\"").trim()
                i++
            }
            val clean = body.filter { it.isNotBlank() }
            if (clean.isNotEmpty() && end - start > 20) cues += Cue(start, end, clean.joinToString("\n"))
        }
        // Collapse the rolling style of auto-captions: drop a leading line repeated from the previous cue.
        val out = mutableListOf<Cue>()
        for (c in cues) {
            val prev = out.lastOrNull()
            val lines2 = c.text.split("\n")
            val text2 = if (prev != null && lines2.size > 1 && lines2.first() == prev.text.split("\n").last()) {
                lines2.drop(1).joinToString("\n")
            } else c.text
            out += c.copy(text = text2)
        }
        return out
    }
}

object Chapters {
    fun of(info: StreamInfo): List<Chapter> =
        info.streamSegments
            .map { Chapter(it.title ?: "", it.startTimeSeconds * 1000L, it.previewUrl) }
            .sortedBy { it.startMs }
}

/** Sleep timer choices in minutes; -1 means "end of video". */
